// UI 언어 전환 (한국어 / English / 日本語).
// 외부 i18n 라이브러리 없이 가볍게: lang이 바뀌면 t()를 호출한 템플릿이 자동 리렌더된다.
// - getLang(): 현재 언어 ('ko' | 'en' | 'ja')
// - setLang(l): 언어 변경 + localStorage 저장
// - toggleLang(): ko → en → ja → ko 순환
// - t(key, params): 번역 조회. 없으면 한국어 폴백, 그것도 없으면 key 그대로.
//   params가 있으면 문자열 안의 {name}을 치환한다.
// - locale(): toLocaleString용 로케일 문자열
// - LANGS: 언어 선택 UI용 목록

export const LANGS = [
  { id: 'ko', label: '한국어' },
  { id: 'en', label: 'English' },
  { id: 'ja', label: '日本語' },
];

const STORAGE_KEY = 'atelier-ai-lang';

function loadLang() {
  try {
    if (typeof localStorage !== 'undefined') {
      const v = localStorage.getItem(STORAGE_KEY);
      if (v === 'en' || v === 'ja') return v;
    }
  } catch {
    /* 무시 */
  }
  return 'ko';
}

let current = $state(loadLang());

export function getLang() {
  return current;
}

export function setLang(l) {
  if (l !== 'ko' && l !== 'en' && l !== 'ja') return;
  current = l;
  try {
    if (typeof localStorage !== 'undefined') localStorage.setItem(STORAGE_KEY, l);
  } catch {
    /* 무시 */
  }
}

export function toggleLang() {
  setLang(current === 'ko' ? 'en' : current === 'en' ? 'ja' : 'ko');
}

export function locale() {
  return current === 'ja' ? 'ja-JP' : current === 'en' ? 'en-US' : 'ko-KR';
}

export function t(key, params) {
  const dict = DICT[current] ?? DICT.ko;
  let s = dict[key] ?? DICT.ko[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

// 백엔드 설정 메타(/api/settings)의 label/description을 현재 언어에 맞게 고른다.
// 템플릿에서 호출하면 getLang()의 $state를 읽으므로 언어 전환 시 자동 리렌더된다.
// m이 없으면 undefined (?? 폴백과 함께 쓰기 위함).
export function metaLabel(m) {
  if (!m) return undefined;
  const l = getLang();
  if (l === 'en') return m.label_en || m.label;
  if (l === 'ja') return m.label_ja || m.label;
  return m.label;
}

export function metaDesc(m) {
  if (!m) return undefined;
  const l = getLang();
  if (l === 'en') return m.description_en || m.description;
  if (l === 'ja') return m.description_ja || m.description;
  return m.description;
}

